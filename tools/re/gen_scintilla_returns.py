#!/usr/bin/env python3
"""Generate the cmd->return-kind table for Scintilla delegation.

Parses src/Scintilla/include/Scintilla.iface (fun/get/set/enu) and
emits scintilla_returns.inc: {cmd, kind} pairs sorted by cmd.
Kinds: v(oid) i(nt) b(ool) p(osition/string-ptr) t(ext=needs marshal)
"""
import re
import sys

iface = open(sys.argv[1] if len(sys.argv) > 1
             else 'src/Scintilla/include/Scintilla.iface').read()
RET = {'void': 'v', 'int': 'i', 'bool': 'b', 'position': 'p',
       'stringresult': 't', 'string': 't', 'textrange': 't'}
rows = []
for m in re.finditer(r'^(fun|get|set)\s+(\w+)\s+\w+\s*=?\s*(\d+)', iface, re.M):
    kind = RET.get(m.group(2), 'i')
    rows.append((int(m.group(3)), kind))
seen = {}
for c, k in rows:
    seen.setdefault(c, k)
out = ['// generated by tools/re/gen_scintilla_returns.py from Scintilla.iface',
       '// {cmd, kind}: v=void i=int b=bool p=position t=text-marshal', '{']
for c in sorted(seen):
    out.append(f'\t{{{c}, \'{seen[c]}\'}},')
out.append('};')
open(sys.argv[2] if len(sys.argv) > 2 else 'src/Sessions/scintilla_returns.inc',
     'w').write('\n'.join(out) + '\n')
print(f'{len(seen)} entries')
